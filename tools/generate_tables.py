"""Generate constant 44.1 kHz oscillator tables. No float needed by the C voice."""
import math
from pathlib import Path
root = Path(__file__).resolve().parents[1]
table = [round(math.sin(2 * math.pi * i / 256) * 32767) for i in range(256)]
inc = [round(440 * 2 ** ((n - 69) / 12) * 2**32 / 44100) for n in range(128)]
text = '/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/generate_tables.py */\n'
text += 'static const int16_t echo_sine[256] = {\n' + ','.join(map(str, table)) + '\n};\n'
text += 'static const uint32_t echo_increments[128] = {\n' + ','.join(str(x)+'u' for x in inc) + '\n};\n'
(root / 'src/voice_tables.h').write_text(text)
